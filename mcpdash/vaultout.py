REPORT_TEMPLATE = """---
mutability: living
type: report
tags: [mcp, tooling, report]
---

# MCP Usage Report

Rolling record of what the MCP toolbox costs and what it earns. Appended by
`mcp_dashboard.py --report`; newest entry first. Method and design:
[[MCP Server Management]].

"""


def append_report(servers, recs, totals_d, now_iso, path=None):
    """Prepend a dated snapshot to the usage report note."""
    path = Path(path or WEEKLY_NOTE)
    ranked = sorted(servers, key=lambda s: -s.get("calls_30d", 0))
    used = [s for s in ranked if s.get("calls_30d", 0) > 0][:5]
    idle = [s for s in ranked if s.get("calls_30d", 0) == 0
            and s.get("ram_bytes", 0) > 0][:5]
    lines = [f"## {now_iso[:10]}", ""]
    lines.append(
        f"- Local RAM: **{fmt_mb(totals_d['ram'])}** across "
        f"{sum(1 for s in servers if s.get('instances'))} running server(s); "
        f"context cost ~{fmt_tokens(totals_d['tokens'])} tokens "
        f"({totals_d['tools']} tools); {totals_d['calls30']} calls in 30 days.")
    if totals_d["reclaimable"]:
        lines.append(f"- Reclaimable by switching off unused servers: "
                     f"**{fmt_mb(totals_d['reclaimable'])}**.")
    if used:
        lines.append("- Most used: " + ", ".join(
            f"{s['name']} ({s['calls_30d']})" for s in used) + ".")
    if idle:
        lines.append("- Costing without calls: " + ", ".join(
            f"{s['name']} ({fmt_mb(s.get('ram_bytes', 0))})" for s in idle) + ".")
    for r in recs[:5]:
        lines.append(f"    - {r['severity']}: {r['title']} — {r['detail']}")
    lines.append("")
    entry = "\n".join(lines)

    if path.exists():
        text = path.read_text(encoding="utf-8")
        if f"\n## {now_iso[:10]}\n" in text:  # replace today's entry
            text = re.sub(r"(?ms)^## " + re.escape(now_iso[:10]) + r"\n.*?(?=^## |\Z)",
                          entry, text)
            path.write_text(text, encoding="utf-8")
            return path
        marker = "[[MCP Server Management]].\n\n"
        if marker in text:
            head, tail = text.split(marker, 1)
            path.write_text(head + marker + entry + tail, encoding="utf-8")
        else:
            path.write_text(text.rstrip() + "\n\n" + entry, encoding="utf-8")
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(REPORT_TEMPLATE + entry, encoding="utf-8")
    return path


