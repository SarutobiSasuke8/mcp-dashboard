"""Vault-facing outputs: the MCP Directory note, a usage report, and tasks.

Everything written here is either inside a generated marker block or an
append — existing prose is never rewritten, per the vault's mutability
conventions.
"""

import datetime
import re
from pathlib import Path

from .common import (REGISTRY_PATH, TASKS_INBOX, WEEKLY_NOTE, fmt_mb,
                     fmt_tokens, load_json, save_json)

NOTE_BEGIN = "<!-- mcp-dashboard:begin (generated - edits inside this block are overwritten) -->"
NOTE_END = "<!-- mcp-dashboard:end -->"
TASK_MARKER = "mcp-dashboard"


# ---------------------------------------------------------------------------
# Registry
# ---------------------------------------------------------------------------

def update_registry(servers, now_iso):
    registry = load_json(REGISTRY_PATH) or {}
    entries = registry.get("servers", {})
    for s in servers:
        e = entries.get(s["key"], {})
        e.update({
            "name": s["name"], "agent": s["agent"], "scope": s["scope"],
            "origin": s["origin"], "transport": s["transport"],
            "command": s["command"], "provenance": s.get("provenance", "unknown"),
            "last_seen": now_iso, "last_status": s.get("status", "unknown"),
            "last_ram_mb": round(s.get("ram_bytes", 0) / 1048576, 1),
            "calls_30d": s.get("calls_30d", 0), "calls": s.get("calls", 0),
            "last_used": s.get("last_used"), "verdict": s.get("verdict", ""),
            "tools": s.get("tools_count", 0), "ctx_tokens": s.get("ctx_tokens", 0),
            "enabled": s.get("enabled", True),
        })
        e.setdefault("first_seen", now_iso)
        e["peak_ram_mb"] = max(e.get("peak_ram_mb", 0), e["last_ram_mb"])
        entries[s["key"]] = e
    registry["servers"] = entries
    registry["last_scan"] = now_iso
    save_json(REGISTRY_PATH, registry)
    return registry


# ---------------------------------------------------------------------------
# MCP Directory note
# ---------------------------------------------------------------------------

def render_note_block(registry, servers, now_iso):
    entries = sorted(registry.get("servers", {}).values(),
                     key=lambda e: (-e.get("last_ram_mb", 0), e["name"]))
    today = now_iso[:10]
    live_keys = {s["key"] for s in servers}
    lines = [
        NOTE_BEGIN,
        f"_Last scan: {registry.get('last_scan', now_iso)}_",
        "",
        "| Server | Agent | Scope | Provenance | Status | Verdict | Calls 30d | Last used | RAM | Peak | Context | First seen |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for e in entries:
        gone = e.get("last_seen", "")[:10] != today
        name = f"~~{e['name']}~~" if gone else f"**{e['name']}**"
        status = "removed from config" if gone else e.get("last_status", "unknown")
        last_used = (e.get("last_used") or "")[:10] or "never"
        lines.append(
            f"| {name} | {e.get('agent', 'claude')} | {e['scope']} "
            f"| {e.get('provenance', 'unknown')} | {status} | {e.get('verdict', '')} "
            f"| {e.get('calls_30d', 0)} | {last_used} "
            f"| {e.get('last_ram_mb', 0):g} MB | {e.get('peak_ram_mb', 0):g} MB "
            f"| {fmt_tokens(e.get('ctx_tokens', 0))} | {e.get('first_seen', '')[:10]} |")
    if not entries:
        lines.append("| _none seen yet_ | | | | | | | | | | | |")
    lines.append(NOTE_END)
    return "\n".join(lines)


DIRECTORY_TEMPLATE = """---
mutability: living
type: dashboard
tags: [mcp, tooling, dashboard]
---

# MCP Directory

Persistent registry of every MCP server this machine has ever had in its
toolbox — Claude Code, Codex, Gemini, and Cursor, current and past.
Generated by `Obsidian Vault Management/Scripts/MCP Dashboard/mcp_dashboard.py`.

Design and build record: [[MCP Server Management]].
Visual dashboard: `MCP Server Dashboard.html` in this folder.

{block}

## Notes

- stdio servers spawn one process tree **per open agent session** — the usual
  cause of MCP RAM drain.
- Label your own servers in `mcp-provenance.json` next to the script.
- Verdicts come from cost weighed against recorded use: `earning`, `quiet`,
  `dormant`, `unused`, `expensive`, `broken`, `disabled`.
"""


def write_directory_note(path, registry, servers, now_iso):
    block = render_note_block(registry, servers, now_iso)
    path = Path(path)
    if path.exists():
        text = path.read_text(encoding="utf-8")
        if NOTE_BEGIN in text and NOTE_END in text:
            pre = text.split(NOTE_BEGIN)[0]
            post = text.split(NOTE_END, 1)[1]
            path.write_text(pre + block + post, encoding="utf-8")
            return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(DIRECTORY_TEMPLATE.format(block=block), encoding="utf-8")


