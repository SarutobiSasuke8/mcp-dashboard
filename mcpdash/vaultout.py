def append_tasks(recs, now_iso, path=None, limit=5):
    """Append high-severity findings to the task inbox, skipping any whose
    title is already present. Returns the list of task lines written."""
    path = Path(path or TASKS_INBOX)
    if not path.exists():
        return []
    text = path.read_text(encoding="utf-8")
    wanted = [r for r in recs if r["severity"] == "high"][:limit]
    new = []
    for r in wanted:
        if r["title"] in text:
            continue
        action = {"disable": "Switch off", "secret": "Move to an env var",
                  "review": "Review"}.get(r["action"], "Review")
        new.append(f"- [ ] {action}: {r['title']} — {r['detail']} "
                   f"[area:: tooling] #task #inbox [source:: {TASK_MARKER}]")
    if not new:
        return []
    section = (f"\n## MCP toolbox hygiene — {now_iso[:10]}\n\n"
               f"Source: [[MCP Directory]] · generated by "
               f"`mcp_dashboard.py --tasks`\n\n" + "\n".join(new) + "\n")
    with open(path, "a", encoding="utf-8") as fh:
        fh.write(section)
    return new
